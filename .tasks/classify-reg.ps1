function Test-Patterns($name, $patterns) {
    foreach ($p in $patterns) {
        if ($name -match $p) { return $true }
    }
    return $false
}

$keep = New-Object System.Collections.Generic.List[string]
$remove = New-Object System.Collections.Generic.List[string]
$review = New-Object System.Collections.Generic.List[string]

foreach ($name in $names) {
    if (Test-Patterns $name $bizPatterns) {
        [void]$remove.Add($name)
    } elseif (Test-Patterns $name $techPatterns) {
        [void]$keep.Add($name)
    } elseif ($pvdSet.Contains($name)) {
        [void]$review.Add($name)
    } else {
        [void]$keep.Add($name)
    }
}

