[void]$sb.AppendLine("REVIEW: $($review.Count)")
[void]$sb.AppendLine('--- KEEP ROWS ---')
$keepRows | ForEach-Object { [void]$sb.AppendLine($_) }
[void]$sb.AppendLine('--- REMOVE ---')
$remove | ForEach-Object { [void]$sb.AppendLine($_) }
[void]$sb.AppendLine('--- REVIEW ---')
$review | ForEach-Object { [void]$sb.AppendLine($_) }
