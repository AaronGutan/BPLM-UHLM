function Get-DirectText([System.Xml.XmlNode]$parent, [string]$name) {
	$el = $parent.SelectSingleNode("./$name")
	if ($null -eq $el) { return $null }
	return $el.InnerText
}

function Ensure-ElementBefore(
	[System.Xml.XmlElement]$parent,
	[string]$name,
	$value,
	[System.Xml.XmlNode]$beforeNode
) {
	$existing = $parent.SelectSingleNode("./$name")
	if ($null -eq $value) {
		if ($null -ne $existing) {
			[void]$parent.RemoveChild($existing)
		}
		return $false
	}

	if ($null -eq $existing) {
		$existing = $parent.OwnerDocument.CreateElement($name)
		if ($null -ne $beforeNode) {
			[void]$parent.InsertBefore($existing, $beforeNode)
		}
		else {
			[void]$parent.AppendChild($existing)
		}
	}
	$existing.InnerText = [string]$value
	return $true
}

function Sync-NamedElements(
	[System.Xml.XmlElement]$sourceRule,
	[System.Xml.XmlElement]$targetRule,
	[string[]]$names,
	[System.Xml.XmlNode]$beforeNode
) {
	$changed = 0
	foreach ($name in $names) {
		$srcVal = Get-DirectText $sourceRule $name
		$tgtVal = Get-DirectText $targetRule $name
		if ($srcVal -eq $tgtVal) { continue }
		[void](Ensure-ElementBefore $targetRule $name $srcVal $beforeNode)
		$changed++
	}
	return $changed
}

