Write-Host "Indexing UH33 PKO..."
$uh33ByCode = @{}
$xpathPkoRules = "//$nPko//$nRule"
foreach ($rule in $uh33.SelectNodes($xpathPkoRules)) {
	$codeEl = $rule.SelectSingleNode("./$nCode")
	if ($null -eq $codeEl) { continue }
	$code = $codeEl.InnerText
	if (-not [string]::IsNullOrWhiteSpace($code) -and -not $uh33ByCode.ContainsKey($code)) {
		$uh33ByCode[$code] = $rule
	}
}

$stats = [ordered]@{
	LightPko           = 0
	Matched            = 0
	MissingInUh33      = 0
	PropertiesReplaced = 0
	SettingsChanged    = 0
	HandlersChanged    = 0
	SearchBefore       = 0
	SearchAfter        = 0
	GlobalHandlersSet  = 0
}

$missing = New-Object System.Collections.Generic.List[string]
$samples = New-Object System.Collections.Generic.List[string]
$xpathSearchProps = ".//$nProperty[@$nSearch='true']"

Write-Host "Merging PKO from light..."
foreach ($srcRule in $light.SelectNodes($xpathPkoRules)) {
	$stats.LightPko++
	$codeEl = $srcRule.SelectSingleNode("./$nCode")
	if ($null -eq $codeEl) { continue }
	$code = $codeEl.InnerText
	if ([string]::IsNullOrWhiteSpace($code)) { continue }

	if (-not $uh33ByCode.ContainsKey($code)) {
		$stats.MissingInUh33++
		$missing.Add($code)
		continue
	}

	$tgtRule = $uh33ByCode[$code]
	$stats.Matched++

	$searchBefore = $tgtRule.SelectNodes($xpathSearchProps).Count
	$stats.SearchBefore += $searchBefore

	# 1) Replace properties
	$srcProps = $srcRule.SelectSingleNode("./$nProperties")
	$tgtProps = $tgtRule.SelectSingleNode("./$nProperties")
	if ($null -ne $srcProps) {
		$imported = $uh33.ImportNode($srcProps, $true)
		if ($null -ne $tgtProps) {
			[void]$tgtRule.ReplaceChild($imported, $tgtProps)
		}
		else {
			$valuesNode = $tgtRule.SelectSingleNode("./$nValues")
			if ($null -ne $valuesNode) {
				[void]$tgtRule.InsertBefore($imported, $valuesNode)
			}
			else {
				[void]$tgtRule.AppendChild($imported)
			}
		}
		$stats.PropertiesReplaced++
	}

	# 2) Sync PKO settings (before Source)
	$beforeSrc = $tgtRule.SelectSingleNode("./$nSource")
	$stats.SettingsChanged += Sync-NamedElements $srcRule $tgtRule $settingsToSync $beforeSrc

	# 3) Sync handlers (before Properties)
	$beforeProps = $tgtRule.SelectSingleNode("./$nProperties")
	$stats.HandlersChanged += Sync-NamedElements $srcRule $tgtRule $handlersToSync $beforeProps

	$searchAfter = $tgtRule.SelectNodes($xpathSearchProps).Count
	$stats.SearchAfter += $searchAfter

	if ($samples.Count -lt 15 -and ($searchBefore -ne $searchAfter -or $searchAfter -gt 0)) {
		$samples.Add("$code : search $searchBefore -> $searchAfter")
	}
}

# 4) Global handlers from light root
$lightRoot = $light.DocumentElement
$uh33Root = $uh33.DocumentElement
$beforeParams = $uh33Root.SelectSingleNode("./$nParams")
if ($null -eq $beforeParams) {
	$beforeParams = $uh33Root.SelectSingleNode("./$nProcessors")
}
if ($null -eq $beforeParams) {
	$beforeParams = $uh33Root.SelectSingleNode("./$nPko")
}

foreach ($name in $globalHandlers) {
	$srcVal = Get-DirectText $lightRoot $name
	$tgtVal = Get-DirectText $uh33Root $name
	if ($srcVal -eq $tgtVal) { continue }
	$hadTarget = ($null -ne $tgtVal)
	$created = Ensure-ElementBefore $uh33Root $name $srcVal $beforeParams
	if ($created -or ($null -eq $srcVal -and $hadTarget)) {
		$stats.GlobalHandlersSet++
	}
}

